"""The property table on the "What gebra checks" page, rendered from the registry (card DOC-21).

The catalog charter rules that counts derive from the registry, so a property's landing moves
no prose count (DEC-35 §3.5 (c)). This module is the documentation's half of that rule. The
table the published pages point at for whether this release checks each catalog property is on
``docs/concepts/what-gebra-checks.md``, between two markers, and this module renders it from
:data:`gebra.verify.registry.PROPERTY_REGISTRY` and the validators the package registers at
import. Prose elsewhere points at the table instead of stating a number, and
``tests/docs/test_property_counts.py`` scans the documentation for count phrasings.

What a row says, and where each cell comes from:

- **ID** — the row's ``property_id``, linked to the property's page under ``docs/validators/``
  when one exists. A page is written when its validator lands, so the link appears with it.
- **Property** — the catalog slug.
- **Claim class** and **Severity** — the row's ``claim_classes`` and ``severities``: every class
  and every severity the catalog states a finding of the property can carry, in catalog order —
  a union, not a pairing, and without the qualifiers the catalog states beside them; each finding
  carries its own pair from the condition registry. For a property with no validator in this
  release they describe the property as the catalog states it, and nothing this release runs.
- **Scope** — the row's ``scope`` token, under the charter's vocabulary.
- **In this release** — *checked* when a validator is registered for the property; otherwise
  *not checked*, with the reason the marker that answers for it gives
  (:data:`gebra.verify.registry.MARKER_REASONS`, keyed by the status dispatch would return).

Usage::

    python tools/property_table.py --write   # re-render the table on the page, in place
    python tools/property_table.py --check   # exit 1 if the committed table is stale

It imports ``gebra.verify`` (which imports no substrate), reads one Markdown page and writes it
back with ``--write``. It builds no workflow, runs no node and opens no connection (WA-07).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Final

from gebra.verify.registry import (
    MARKER_REASONS,
    PROPERTY_SLUGS,
    PropertyEntry,
    is_implemented,
    not_implemented,
    property_entry,
)

#: The repository root — this file lives in ``tools/``.
REPO_ROOT: Final = Path(__file__).resolve().parents[1]

#: The page the table lives on.
PAGE: Final = REPO_ROOT / "docs" / "concepts" / "what-gebra-checks.md"

#: The two markers the table sits between, each on a line of its own. Their comment namespace
#: is ``gebra-property-table:``, deliberately not ``gebra:``: the examples harness refuses an
#: unknown ``gebra:`` directive (``tools/docs_examples.py``), so the namespaces stay disjoint.
BEGIN: Final = (
    "<!-- gebra-property-table:begin — generated by tools/property_table.py from the property "
    "registry; edit the registry, then run `python tools/property_table.py --write`. "
    "CI runs `--check`. -->"
)
END: Final = "<!-- gebra-property-table:end -->"

#: The table's header and alignment rows.
HEADER: Final = "| ID | Property | Claim class | Severity | Scope | In this release |"
ALIGNMENT: Final = "|---|---|---|---|---|---|"

#: What the last column says of a property a validator answers for.
CHECKED: Final = "checked"


class PropertyTableError(ValueError):
    """The page does not carry exactly one well-formed pair of table markers."""


def validator_page(entry: PropertyEntry, *, root: Path = REPO_ROOT) -> Path:
    """Where the property's own page lives: ``docs/validators/p<nn>-<slug>.md`` under ``root``."""
    number = entry.property_id.removeprefix("P-")
    return root / "docs" / "validators" / f"p{number}-{entry.slug}.md"


def status(entry: PropertyEntry) -> str:
    """The last column: *checked*, or *not checked* with the reason its marker states.

    Read the way dispatch reads it: a registered validator answers with a verdict, and a
    property with none is answered by :func:`~gebra.verify.registry.not_implemented`, whose
    status keys the reason every marker surface states beside it.
    """
    if is_implemented(entry.slug):
        return CHECKED
    return f"not checked — {MARKER_REASONS[not_implemented(entry.slug).status]}"


def row(entry: PropertyEntry, *, root: Path = REPO_ROOT) -> str:
    """One table row for ``entry``, its ID linked when ``root`` holds the property's page."""
    page = validator_page(entry, root=root)
    identifier: str = entry.property_id
    if page.is_file():
        identifier = f"[{entry.property_id}](../validators/{page.name})"
    cells = (
        identifier,
        f"`{entry.slug}`",
        ", ".join(claim_class.upper() for claim_class in entry.claim_classes),
        ", ".join(severity.upper() for severity in entry.severities),
        f"`{entry.scope}`",
        status(entry),
    )
    return "| " + " | ".join(cells) + " |"


def render_table(*, root: Path = REPO_ROOT) -> str:
    """The whole table, one row per catalog property in catalog order, markers included."""
    rows = [row(property_entry(slug), root=root) for slug in PROPERTY_SLUGS]
    return "\n".join((BEGIN, HEADER, ALIGNMENT, *rows, END))


def splice(page: str, table: str) -> str:
    """``page`` with the text from its begin marker to its end marker replaced by ``table``.

    Raises:
        PropertyTableError: if either marker is missing, appears more than once, is not on a
            line of its own, or the end marker comes first.
    """
    lines = page.split("\n")
    for marker in (BEGIN, END):
        if sum(line == marker for line in lines) != 1:
            raise PropertyTableError(
                f"the page must carry exactly one line reading {marker!r}; "
                f"found {sum(line == marker for line in lines)}"
            )
    start, stop = lines.index(BEGIN), lines.index(END)
    if stop < start:
        raise PropertyTableError("the end marker comes before the begin marker")
    return "\n".join([*lines[:start], table, *lines[stop + 1 :]])


def main(argv: list[str] | None = None) -> int:
    """``--write`` the table into the page, or ``--check`` that the committed one is current."""
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="re-render the table on the page")
    group.add_argument("--check", action="store_true", help="fail if the committed table is stale")
    args = parser.parse_args(argv)

    where = PAGE.relative_to(REPO_ROOT)
    current = PAGE.read_text(encoding="utf-8")
    try:
        fresh = splice(current, render_table())
    except PropertyTableError as error:
        print(f"{where}: {error}", file=sys.stderr)
        return 1

    if args.write:
        PAGE.write_text(fresh, encoding="utf-8")
        print(f"wrote the property table on {where} — {len(PROPERTY_SLUGS)} rows")
        return 0
    if current != fresh:
        print(
            f"the property table on {where} is not what the registry renders. "
            "Run `python tools/property_table.py --write`."
        )
        return 1
    print(f"the property table on {where} is current — {len(PROPERTY_SLUGS)} rows")
    return 0


if __name__ == "__main__":  # pragma: no cover - exercised through `main` in the test suite
    raise SystemExit(main())
